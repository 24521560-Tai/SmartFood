package com.example.androidapp.model;

public class AddFoodResponse {

    private String message;
    private int id;
    private String name;
    private String imageUrl;

    public String getMessage() {
        return message;
    }

    public int getId() {
        return id;
    }

    public String getName() {
        return name;
    }

    public String getImageUrl() {
        return imageUrl;
    }
}